package Collections;

import java.util.LinkedList;

public class LinkedListDemo1 {

    public static void main(String[] args) {

        // Create LinkedList
        LinkedList<String> names = new LinkedList<>();

        // Add elements
        names.add("RAJU");
        names.add("KIRAN");
        names.add("ARUN");
        names.add("SURESH");

        // Display
        System.out.println(names);
    }
}